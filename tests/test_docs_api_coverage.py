"""fl-044: docstring coverage of the public API, and the docstring pass changing nothing.

`api_coverage` must report no undocumented public class or function in the shipped
packages, and must catch an undocumented symbol in a module built on the fly. The
fl-038 checksums pin behavior: a docstring-only pass must leave every one unchanged.
"""
import sys
import textwrap
import types
from dataclasses import dataclass
from pathlib import Path

import pytest

from frictionlab import bench
from frictionlab.docs_site import api_ref

BASELINE = Path(__file__).resolve().parents[1] / "benchmarks" / "baseline_small.json"


def make_module(name, source, monkeypatch, all_=None):
    """Register an in-memory module `name` executed from `source`."""
    mod = types.ModuleType(name)
    mod.__doc__ = "Temporary module."
    exec(compile(textwrap.dedent(source), f"<{name}>", "exec"), mod.__dict__)
    if all_ is not None:
        mod.__all__ = all_
    monkeypatch.setitem(sys.modules, name, mod)
    return mod


def test_shipped_packages_are_fully_documented():
    missing = api_ref.api_coverage(api_ref.PACKAGES)
    assert missing == [], "undocumented public symbols:\n" + "\n".join(missing)


def test_default_argument_covers_every_package():
    assert api_ref.api_coverage() == api_ref.api_coverage(api_ref.PACKAGES) == []
    assert api_ref.PACKAGES == ("core", "costs", "markets", "agents", "analysis",
                                "experiments", "config", "bench", "cli")


def test_undocumented_function_in_temp_module_is_reported(monkeypatch):
    mod = make_module("fl_tmp_api_a", """
        def documented(x):
            '''Has a docstring.'''
            return x

        def bare(x, y=3):
            return x + y

        class Plain:
            def method(self):
                return 1

        class Fine:
            '''Documented class.'''
        """, monkeypatch)
    assert api_ref.public_names(mod) == ["documented", "bare", "Plain", "Fine"]
    assert api_ref.api_coverage([mod]) == ["fl_tmp_api_a.Plain", "fl_tmp_api_a.bare"]
    assert mod.bare(1) == 4                                  # reporting never mutates


def test_all_controls_the_public_set(monkeypatch):
    mod = make_module("fl_tmp_api_b", """
        def hidden():
            return 0

        def shown():
            return 1

        LIMIT = 5
        """, monkeypatch, all_=["shown", "LIMIT"])
    syms = {s.name: s.kind for s in api_ref.collect(mod)}
    assert syms == {"LIMIT": "data", "shown": "function"}     # data never needs a docstring
    assert api_ref.api_coverage([mod]) == ["fl_tmp_api_b.shown"]


def test_reexports_from_foreign_modules_are_not_public_without_all(monkeypatch):
    mod = make_module("fl_tmp_api_c", """
        from fractions import Fraction
        from os.path import join

        def local():
            pass
        """, monkeypatch)
    assert api_ref.public_names(mod) == ["local"]


def test_autogenerated_dataclass_doc_does_not_count():
    @dataclass
    class Point:
        x: int = 0

    @dataclass
    class Named:
        """A documented point."""
        x: int = 0

    assert Point.__doc__.startswith("Point(")
    assert api_ref.own_doc(Point) == "" and api_ref.own_doc(Named) == "A documented point."


def test_inherited_docstring_does_not_count(monkeypatch):
    mod = make_module("fl_tmp_api_d", """
        class Base:
            '''Base doc.'''

        class Child(Base):
            pass
        """, monkeypatch)
    assert api_ref.api_coverage([mod]) == ["fl_tmp_api_d.Child"]


def test_every_public_member_docstring_is_a_clean_paragraph():
    for pkg in api_ref.PACKAGES:
        for s in api_ref.collect(pkg):
            if s.kind != "data":
                first = api_ref.summary(s.doc)
                assert first and "\n" not in first, s.qualname


@pytest.mark.parametrize("name", list(bench.SCENARIOS))
def test_fl038_checksums_unchanged_by_docstring_pass(name):
    ref = bench.load_json(BASELINE)["scenarios"][name]
    work = bench.get_scenario(name).run("small")
    assert work.checksum == ref["checksum"], name
    assert (work.ops, work.trades, work.volume) == (ref["ops"], ref["trades"], ref["volume"])
